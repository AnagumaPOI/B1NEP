(function () {
  function esc(s) {
    return String(s)
      .replace(/&/g, '&amp;')
      .replace(/</g, '&lt;')
      .replace(/>/g, '&gt;')
      .replace(/"/g, '&quot;');
  }

  function fmt(value, fallback) {
    const n = Number(value);
    return Number.isFinite(n) ? String(value) : fallback;
  }

  function installSimpleWatDesigner(opts) {
    const {
      model,
      rerenderStages,
      refreshProfile,
      wallTotalLength,
      getPyBridge,
      setSiteWaterLevel,
    } = opts || {};

    function layerAnalysis(layer) {
      return layer && layer.analysis === 'total' ? 'total' : 'effective';
    }

    function defaultDrain(layer) {
      return layerAnalysis(layer) === 'total' ? 'undrained' : 'drained';
    }

    function ensureModal() {
      if (document.getElementById('simpleWatDesignerModal')) return;
      const wrapper = document.createElement('div');
      wrapper.innerHTML = `
        <div id="simpleWatDesignerModal" class="modal-backdrop" aria-hidden="true">
          <div class="modal-card" role="dialog" aria-modal="true" aria-labelledby="simpleWatDesignerTitle" style="width:920px;">
            <div class="modal-head">
              <div id="simpleWatDesignerTitle" class="modal-title">Simple WAT Builder</div>
              <button class="modal-close" type="button" data-swd-close="1">×</button>
            </div>
            <div class="modal-grid">
              <label for="swdInitialGwl">Initial water level, z (m)</label>
              <input id="swdInitialGwl" type="text" value="1.0">
            </div>
            <div class="maker-supports" style="margin-top:10px;">
              <table>
                <thead>
                  <tr>
                    <th style="width:54px;">ID</th>
                    <th>Soil layer</th>
                    <th style="width:110px;">Analysis</th>
                    <th style="width:80px;">c</th>
                    <th style="width:80px;">phi</th>
                    <th style="width:160px;">Draining condition</th>
                  </tr>
                </thead>
                <tbody id="swdLayerRows"></tbody>
              </table>
            </div>
            <div class="maker-note" style="margin-top:8px; line-height:1.55;">
              <div>Water pressure is generated by <code>water_stage_solver.py</code> and inserted as WAT commands.</div>
              <div>If a layer is undrained, it uses the previous excavation stage water pressure.</div>
            </div>
            <div class="modal-actions">
              <button type="button" data-swd-close="1">Cancel</button>
              <button type="button" id="swdApply">Apply WAT to stages</button>
            </div>
          </div>
        </div>`;
      document.body.appendChild(wrapper.firstElementChild);

      const modal = document.getElementById('simpleWatDesignerModal');
      modal.addEventListener('click', (e) => {
        if (e.target === modal || e.target.closest('[data-swd-close="1"]')) closeSimpleWatDesigner();
      });
      document.getElementById('swdApply').addEventListener('click', () => applyWatToStages());
    }

    function seedRowsFromModel() {
      ensureModal();
      const waterEl = document.getElementById('swdInitialGwl');
      if (waterEl) waterEl.value = fmt(model && model.wall && model.wall.w_depth, '1.0');
      const host = document.getElementById('swdLayerRows');
      if (!host) return;
      host.innerHTML = '';
      (model.layers || []).forEach((layer, idx) => {
        const tr = document.createElement('tr');
        const analysis = layerAnalysis(layer);
        const drain = layer.drain_condition === 'drained' || layer.drain_condition === 'undrained'
          ? layer.drain_condition
          : defaultDrain(layer);
        tr.innerHTML = `
          <td>${idx + 1}</td>
          <td>${esc(layer.type || `Soil Layer ${idx + 1}`)}</td>
          <td>${esc(analysis)}</td>
          <td>${esc(fmt(layer.c, ''))}</td>
          <td>${esc(fmt(layer.phi, ''))}</td>
          <td>
            <select data-swd-drain="${idx}" style="width:140px;">
              <option value="drained"${drain === 'drained' ? ' selected' : ''}>Drained</option>
              <option value="undrained"${drain === 'undrained' ? ' selected' : ''}>Undrained</option>
            </select>
          </td>`;
        host.appendChild(tr);
      });
      if (!(model.layers || []).length) {
        const tr = document.createElement('tr');
        tr.innerHTML = '<td colspan="6" style="color:#778;">No soil layers defined.</td>';
        host.appendChild(tr);
      }
    }

    function solverLayersFromDesigner() {
      let top = 0;
      return (model.layers || []).map((layer, idx) => {
        const bottom = Number(layer && layer.depth);
        const sel = document.querySelector(`[data-swd-drain="${idx}"]`);
        const drain = sel && sel.value === 'undrained' ? 'undrained' : 'drained';
        if (layer) layer.drain_condition = drain;
        const out = {
          top,
          bottom,
          analysis_mode: drain === 'undrained' ? 'total' : 'effective',
          c: Number(layer && layer.c),
          phi: Number(layer && layer.phi),
          name: String(layer && layer.type || `Soil Layer ${idx + 1}`),
          original_analysis: layerAnalysis(layer),
          drain_condition: drain,
        };
        top = bottom;
        return out;
      }).filter(layer => Number.isFinite(layer.bottom) && layer.bottom > layer.top);
    }

    function excavationStagesFromModel() {
      const stages = Array.isArray(model.stages) ? model.stages : [];
      const out = [];
      stages.forEach((stage, stageIdx) => {
        let excavationLevel = null;
        (stage.actions || []).forEach(action => {
          if (action && action.type === 'EXC') {
            const z = Number(action.Z1);
            if (Number.isFinite(z)) excavationLevel = z;
          }
        });
        if (excavationLevel != null) {
          out.push({ stage, stage_idx: stageIdx, stage_id: stageIdx + 1, excavation_level: excavationLevel });
        }
      });
      return out;
    }

    function buildPayload(excavationStages, initialGwl) {
      return {
        initial_gwl: initialGwl,
        retained_water_level: initialGwl,
        wall_depth: Number(wallTotalLength ? wallTotalLength() : 0),
        layers: solverLayersFromDesigner(),
        stages: excavationStages.map(item => ({
          stage_id: item.stage_id,
          excavation_level: Number(item.excavation_level),
          pumping: { points: [] },
        })),
      };
    }

    function solveWaterStages(payload) {
      return new Promise((resolve, reject) => {
        const bridge = (typeof getPyBridge === 'function' && getPyBridge())
          || window.pyBridge
          || (window.parent && window.parent.pyBridge)
          || (window.opener && window.opener.pyBridge)
          || null;
        if (!bridge || !bridge.solveWaterStages) {
          reject(new Error('water stage solver requires the Python bridge.'));
          return;
        }
        bridge.solveWaterStages(JSON.stringify(payload), function(reply) {
          try {
            const data = JSON.parse(reply || '{}');
            if (!data.ok) throw new Error(data.error || 'water solver failed');
            resolve(data);
          } catch (err) {
            reject(err);
          }
        });
      });
    }

    function insertWat(stage, watCommands, solverResult) {
      if (!stage || !Array.isArray(stage.actions)) return;
      stage.actions = stage.actions.filter(action => action && action.type !== 'WAT');
      const insertAt = stage.actions.findIndex(action => action.type === 'CAL' || action.type === 'ENV');
      const commands = Array.isArray(watCommands) ? watCommands.map(action => Object.assign({ water_designer: true }, action)) : [];
      if (insertAt >= 0) stage.actions.splice(insertAt, 0, ...commands);
      else stage.actions.push(...commands);
      stage.water_solver = solverResult;
    }

    async function applyWatToStages() {
      const initialGwl = Number(document.getElementById('swdInitialGwl')?.value);
      if (!Number.isFinite(initialGwl) || initialGwl < 0) {
        alert('Please enter a valid initial water level.');
        return;
      }
      const excavationStages = excavationStagesFromModel();
      if (!excavationStages.length) {
        alert('No excavation stages found. Generate or add EXC stages first.');
        return;
      }
      const wallDepth = Number(wallTotalLength ? wallTotalLength() : 0);
      if (!(wallDepth > 0)) {
        alert('Please define the retaining wall depth before applying WAT.');
        return;
      }

      if (typeof setSiteWaterLevel === 'function') setSiteWaterLevel(initialGwl);
      else if (model && model.wall) model.wall.w_depth = initialGwl;

      const payload = buildPayload(excavationStages, initialGwl);
      let solved;
      try {
        solved = await solveWaterStages(payload);
      } catch (err) {
        alert(err && err.message ? err.message : String(err));
        return;
      }

      const byStageId = new Map();
      (solved.stages || []).forEach(result => byStageId.set(Number(result.stage_id), result));
      excavationStages.forEach(item => {
        const result = byStageId.get(Number(item.stage_id));
        if (!result) return;
        insertWat(item.stage, result.wat_commands, result);
      });

      if (typeof rerenderStages === 'function') rerenderStages();
      if (typeof refreshProfile === 'function') refreshProfile();
      closeSimpleWatDesigner();
    }

    function openSimpleWatDesigner() {
      ensureModal();
      seedRowsFromModel();
      const modal = document.getElementById('simpleWatDesignerModal');
      modal.classList.add('show');
      modal.setAttribute('aria-hidden', 'false');
      modal.style.display = 'flex';
      modal.style.zIndex = '9000';
    }

    function closeSimpleWatDesigner() {
      const modal = document.getElementById('simpleWatDesignerModal');
      if (!modal) return;
      modal.classList.remove('show');
      modal.setAttribute('aria-hidden', 'true');
      modal.style.display = 'none';
    }

    ensureModal();
    window.openSimpleWatDesigner = openSimpleWatDesigner;
    window.closeSimpleWatDesigner = closeSimpleWatDesigner;
    return { openModal: openSimpleWatDesigner, closeModal: closeSimpleWatDesigner };
  }

  window.installSimpleWatDesigner = installSimpleWatDesigner;
})();
